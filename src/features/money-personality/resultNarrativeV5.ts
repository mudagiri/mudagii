export function buildMoneyResultExperienceV5(evaluation:EngineEvaluation,base:MoneyResultExperienceV2):MoneyResultExperienceV4{
  const v4=buildMoneyResultExperienceV4(evaluation,base);
  if(!evaluation.jobCode||!evaluation.style.primary)throw new Error('Result V5 requires a complete evaluation');
  const mirror=CONCRETE_MIRROR[evaluation.jobCode][evaluation.style.primary];
  return {
    ...v4,
    heroLine:mirror.heroLine,
    identityTitle:mirror.identityTitle,
    resonanceChecks:mirror.resonanceChecks,
    // Make the detailed section explain the actual decision scene and the
    // contradiction behind it, instead of repeating a generic type summary.
    typeMeaning:`${v4.sceneBody} ${v4.hiddenConflict}`,
  };
}
