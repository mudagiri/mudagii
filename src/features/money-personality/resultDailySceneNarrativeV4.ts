const STYLE_LAST:Record<StyleId,string>={
  DRIVE:'で、これで今より動きやすくなる？',
  ENJOY:'で、払ったあと「これでよかった」って思える？',
  SECURE:'で、決めたあとに困る要素は残ってない？',
  OPTIMIZE:'で、要らないものにまで払ってない？',
};

function plainLabel(label:string){return label.replace(/^\S+\s+/,'')}

function axisBridge(axes:JobAxes){
  if(axes.decision==='D'&&axes.time==='F')return '一回条件とこの先まで見よ。';
  if(axes.decision==='D'&&axes.time==='I')return '今必要なのは分かる。条件だけ確認しよ。';
  if(axes.decision==='N'&&axes.time==='F')return '先のことは一応見る。でも最後は自分に合う方。';
  return '条件は見る。でも最後に「こっち」が残るなら無視しにくい。';
}

function vividVoice(scene:DailyScene,axes:JobAxes,style:StyleId){
  const key=plainLabel(scene.label);
  const thought=THOUGHT[key]??`${key}なら、今の自分はどっちを選ぶ？`;
  return `「${thought} ${axisBridge(axes)} ${STYLE_LAST[style]}」`;
}

/**
 * V4 keeps the V3 measured scenario selection, but makes the inner monologue
 * scene-specific. It stays hypothetical: these are recognition prompts, not
 * claims that the user has actually made a specific purchase or decision.
 */
export function dailyScenesForType(jobCode:JobCode,style:StyleId,count=6):DailyScene[]{
  const axes=JOB_AXES[jobCode];
  return v3DailyScenesForType(jobCode,style,count).map(scene=>({
    ...scene,
    voice:vividVoice(scene,axes,style),
  }));
}
