import {compareTravel,compareWork,makeMeetingPreview} from './chapter3-life-fork-v21.mjs';
let checks=0;const errors=[];
const assert=(v,n)=>{checks++;if(!v)errors.push(n)};
const t=compareTravel({windowYears:3,tripsPerYear:2,costPerTripYen:200000,alternativeCostPerTripYen:150000});
assert(t.status==='ready','travel valid');
assert(t.scenarioA.count===3&&t.scenarioB.count===6,'3 years opportunity');
assert(t.differenceInOpportunities===3,'opportunities delta');
assert(t.scenarioA.budgetYen===600000,'travel A');
assert(t.scenarioB.budgetYen===1200000,'travel B');
assert(t.scenarioC.budgetYen===900000,'travel C');
assert(t.neverAssumeFamily,'no assumed child');
assert(compareTravel({windowYears:3,tripsPerYear:2}).scenarioB.budgetYen===null,'no invented budget');
assert(compareTravel({windowYears:0,tripsPerYear:2}).status==='unknown','zero years');
assert(compareTravel({windowYears:3,tripsPerYear:0}).status==='unknown','zero trips');
assert(compareTravel({windowYears:3,tripsPerYear:2,costPerTripYen:-1}).status==='unknown','negative money');
assert(compareTravel({windowYears:3,tripsPerYear:2,costPerTripYen:NaN}).status==='unknown','NaN');
assert(compareTravel({windowYears:40,tripsPerYear:12}).scenarioB.count===480,'max bounds');
const w=compareWork({earlyAge:55,lateAge:60,endAge:65,currentWorkdays:5,desiredWorkdays:3,monthlyNetIncomeDifferenceYen:150000});
assert(w.status==='ready','work valid');
assert(w.scenarioA.scheduledWorkdaysDifference===1040,'earlier days');
assert(w.scenarioB.scheduledWorkdaysDifference===520,'later days');
assert(w.deltaScheduledWorkdays===520,'difference days');
assert(w.scenarioA.netIncomeDifferenceYen===18000000,'income A');
assert(w.scenarioB.netIncomeDifferenceYen===9000000,'income B');
assert(w.isAffordabilityAssessment===false,'not gap');
assert(compareWork({earlyAge:55,lateAge:60,endAge:65,currentWorkdays:5,desiredWorkdays:3}).scenarioA.netIncomeDifferenceYen===null,'no money assumed');
assert(compareWork({earlyAge:65,lateAge:60,endAge:70,currentWorkdays:5,desiredWorkdays:3}).status==='unknown','start order');
assert(compareWork({earlyAge:55,lateAge:60,endAge:60,currentWorkdays:5,desiredWorkdays:3}).status==='unknown','end order');
assert(compareWork({earlyAge:55,lateAge:60,endAge:65,currentWorkdays:3,desiredWorkdays:5}).status==='unknown','reverse days');
assert(compareWork({earlyAge:55,lateAge:60,endAge:65,currentWorkdays:5,desiredWorkdays:3,monthlyNetIncomeDifferenceYen:-1}).status==='unknown','negative income');
const m=makeMeetingPreview({type:'travel',chosenPath:'b',travel:t,keepEverydayJoy:true});
assert(m.status==='ready'&&m.summary.includes('普段の楽しみを守りながら'),'consult choice and preserve');
assert(m.booked===false&&m.shared===false&&m.consentRequired===true,'consult never booked');
assert(!/円|収入|diagnosisId/.test(m.summary),'consult no automatic finance');
assert(makeMeetingPreview({type:'travel',chosenPath:'c',travel:compareTravel({windowYears:3,tripsPerYear:2})}).status==='unavailable','no invented budget route C');
assert(makeMeetingPreview({type:'work',chosenPath:'a',work:w}).summary.includes('55歳'),'work consult personalized');
assert(makeMeetingPreview({type:'work',chosenPath:'bad',work:w}).status==='unavailable','invalid choice');
if(errors.length){console.error(JSON.stringify({status:'FAIL',checks,errors},null,2));process.exitCode=1;}
else console.log(JSON.stringify({status:'PASS',checks,scope:'V2.1 pure pilot arithmetic and consent boundary, not proof of consumer insight'}));
