import {workFreedomAha,travelAha} from './chapter3-aha-experiment-v1.mjs';
let n=0;let fails=[];function check(ok,name){n++;if(!ok)fails.push(name)}
let x=workFreedomAha({currentAge:35,changeAtAge:55,bridgeUntilAge:65,monthlyIncomeGapYen:150000,monthlyInvestmentYen:50000});
check(x.status==='conditional_insight','valid bridge');
check(x.calculated.bridgeYen===18000000,'nominal 18m');
check(x.calculated.months===120,'120 bridge months');
check(x.calculated.contributedPrincipal===12000000,'20y contributions only');
check(x.caveat.includes('判定しない'),'no investment guarantee');
check(x.insightProven===false,'user insight unproven');
check(x.investmentContext.includes('差し引きしません'),'no false shortfall');
check(workFreedomAha({currentAge:35,changeAtAge:55,bridgeUntilAge:65}).status==='need_data','need gap');
check(workFreedomAha({currentAge:35,changeAtAge:55,bridgeUntilAge:55,monthlyIncomeGapYen:1000}).status==='need_data','no equal age');
check(workFreedomAha({currentAge:35,changeAtAge:55,bridgeUntilAge:65,monthlyIncomeGapYen:NaN}).status==='need_data','NaN rejected');
check(workFreedomAha({currentAge:35,changeAtAge:55,bridgeUntilAge:65,monthlyIncomeGapYen:-1}).status==='need_data','negative rejected');
check(workFreedomAha({currentAge:55,changeAtAge:35,bridgeUntilAge:65,monthlyIncomeGapYen:10000}).status==='need_data','age order');
x=travelAha({tripsPerYear:2,costPerTripYen:200000,chapter2CandidateUpperMonthlyYen:12000});
check(x.status==='conditional_insight','valid travel');
check(x.calculated.annual===400000,'annual 400k');
check(x.calculated.monthly===33334,'monthly ceil');
check(x.calculated.scenario.ifAllCandidatesRealizedYen===144000,'candidate conditional year');
check(x.calculated.scenario.hypotheticalPortionPercent===36,'conditional 36%');
check(x.calculated.scenario.hypotheticalRemainingYen===256000,'conditional rest');
check(x.calculated.scenario.guaranteed===false,'no guaranteed saved cash');
check(x.householdBridge.includes('未確定'),'unconfirmed label');
check(x.caveat.includes('判定していない'),'not affordable claim');
check(x.insightProven===false,'actual aha unproven');
check(travelAha({tripsPerYear:2}).status==='need_data','needs cost');
check(travelAha({tripsPerYear:0,costPerTripYen:200000}).status==='need_data','no zero trips');
check(travelAha({tripsPerYear:2,costPerTripYen:-1}).status==='need_data','negative rejected');
check(travelAha({tripsPerYear:2,costPerTripYen:0}).status==='need_data','zero budget not passed as insight');
check(travelAha({tripsPerYear:2,costPerTripYen:200000}).calculated.scenario===null,'no candidate no invented money');
check(travelAha({tripsPerYear:2,costPerTripYen:200000,chapter2CandidateUpperMonthlyYen:0}).calculated.scenario.guaranteed===false,'zero candidate still hypothetical');
if(fails.length){console.error(JSON.stringify({status:'FAIL',tests:n,fails}));process.exitCode=1}else console.log(JSON.stringify({status:'PASS',tests:n,scope:'2 hypotheses, conditional arithmetic only; not a live diagnostic or proven insight'}));
