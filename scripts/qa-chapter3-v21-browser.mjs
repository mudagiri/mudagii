import {chromium,webkit} from 'playwright';
import fs from 'node:fs';
import path from 'node:path';
const engine=process.env.BROWSER_ENGINE==='webkit'?'webkit':'chromium';
const browser=await (engine==='webkit'?webkit:chromium).launch({headless:true});
const url=process.env.CHAPTER3_URL||'http://127.0.0.1:4173/chapter3-v21.html';
const out=path.resolve('chapter3-v21-qa');fs.mkdirSync(out,{recursive:true});
const widths=[320,375,390,430],errors=[];
const assert=(ok,why)=>{if(!ok)errors.push(why);};
for(const width of widths){
 const ctx=await browser.newContext({viewport:{width,height:844},deviceScaleFactor:1,reducedMotion:'reduce'});
 const page=await ctx.newPage(),outside=[];
 page.on('pageerror',e=>errors.push(width+' runtime '+String(e)));
 page.on('request',r=>{if(/script.google.com|analytics|line.me|\/exec\b|\/booking\b/i.test(r.url()))outside.push(r.url());});
 await page.goto(url,{waitUntil:'networkidle'});
 await page.locator('[data-v21=true]').waitFor();
 assert(await page.locator('.f21-handoff img').evaluate(e=>e.complete&&e.naturalWidth>0),width+' official JOB image');
 assert(await page.locator('.f21-talk img').evaluate(e=>e.complete&&e.naturalWidth>0),width+' official mascot image');
 assert((await page.locator('.f21-record').innerText()).includes('未鑑定'),width+' unconfirmed chest');
 await page.screenshot({path:path.join(out,engine+'-'+width+'-intro.png'),fullPage:true});
 await page.getByRole('button',{name:/旅行・体験を増やしたい/}).click();
 await page.getByRole('button',{name:/子どもが今の年齢のうちに/}).click();
 await page.getByRole('button',{name:/この未来の分岐を見る/}).click();
 await page.getByRole('button',{name:/仮想の条件を入れて比較/}).click();
 assert(await page.locator('.f21-example').isVisible(),width+' explicit mock assumption');
 const forks=await page.locator('.f21-compare').innerText();
 assert(forks.includes('3回')&&forks.includes('6回'),width+' 3y opportunities');
 assert(forks.includes('600,000円')&&forks.includes('1,200,000円'),width+' 3y nominal budget');
 await page.screenshot({path:path.join(out,engine+'-'+width+'-travel-forks.png'),fullPage:true});
 await page.getByRole('button',{name:/年2回のペース/}).click();
 await page.getByRole('button',{name:/選んだ道から攻略書を見る/}).click();
 assert((await page.locator('.f21-value').innerText()).includes('6回'),width+' 6 trip result');
 const meetPreview=await page.locator('.f21-meeting').innerText();
 assert(meetPreview.includes('3年間で年2回'),width+' personalized meeting topic');
 assert(!(await page.locator('.f21-share').innerText()).includes('子ども'),width+' share excludes child');
 assert(!(await page.locator('.f21-share').innerText()).includes('1,200,000'),width+' share excludes money');
 assert(await page.locator('.f21-consent').count()===0,width+' share preview not auto opened');
 await page.getByLabel(/面談でこのテーマを相談することに興味/).check();
 assert((await page.locator('.f21-consent').innerText()).includes('送信はしません'),width+' consent preview without sending');
 await page.screenshot({path:path.join(out,engine+'-'+width+'-travel-reward.png'),fullPage:true});
 await page.getByRole('button',{name:/別の未来でもう一度試す/}).click();
 await page.getByRole('button',{name:/働く時間を自分で選びたい/}).click();
 await page.getByRole('button',{name:/働く日数を減らしたい/}).click();
 await page.getByRole('button',{name:/この未来の分岐を見る/}).click();
 await page.getByRole('button',{name:/仮想の条件を入れて比較/}).click();
 const workForks=await page.locator('.f21-compare').innerText();
 assert(workForks.includes('1,040日')&&workForks.includes('520日'),width+' work schedule delta');
 assert(workForks.includes('保証しない'),width+' no promised free time');
 await page.screenshot({path:path.join(out,engine+'-'+width+'-work-forks.png'),fullPage:true});
 await page.getByRole('button',{name:/55歳から働く日数を変える/}).click();
 await page.getByRole('button',{name:/選んだ道から攻略書を見る/}).click();
 assert((await page.locator('.f21-meeting').innerText()).includes('55歳から'),width+' specific work meeting');
 await page.locator('.f21-details summary').click();
 assert((await page.locator('.f21-details').innerText()).includes('未確定'),width+' money semantics');
 await page.screenshot({path:path.join(out,engine+'-'+width+'-work-reward.png'),fullPage:true});
 await page.getByRole('button',{name:/別の未来でもう一度試す/}).click();
 await page.getByRole('button',{name:/旅行・体験を増やしたい/}).click();
 await page.getByRole('button',{name:/まだ決めていない/}).click();
 await page.getByRole('button',{name:/この未来の分岐を見る/}).click();
 await page.getByRole('button',{name:/旅行の回数を選んでみる/}).click();
 await page.getByRole('button',{name:/選んだ道から攻略書を見る/}).click();
 assert(await page.locator('.f21-value').count()===0,width+' unknown no made-up figure');
 assert(!(await page.locator('.f21-choice').innerText()).includes('子ども'),width+' no child assumption');
 const metrics=await page.evaluate(()=>({width:window.innerWidth,scroll:document.documentElement.scrollWidth}));
 assert(metrics.scroll<=width+1,width+' horizontal overflow scrollWidth='+metrics.scroll);
 assert(outside.length===0,width+' no external service calls');
 await ctx.close();
}
await browser.close();
if(errors.length){console.error(JSON.stringify({status:'FAIL',engine,errors},null,2));process.exitCode=1;}
else console.log(JSON.stringify({status:'PASS',engine,widths,screenshots:widths.length*5,scope:'V2.1 isolated choice & meeting-preview UX; no real users or booking'}));
